import { assertSvgSize } from "../core/limits";

const SVG_NS = "http://www.w3.org/2000/svg";
let nextDiagramId = 0;

const ALLOWED_ELEMENTS = new Set([
  "svg",
  "g",
  "a",
  "circle",
  "ellipse",
  "line",
  "path",
  "polygon",
  "polyline",
  "rect",
  "text",
  "title",
  "defs",
  "linearGradient",
  "radialGradient",
  "stop",
]);

const GRADIENT_ATTRIBUTES: Record<string, ReadonlySet<string>> = {
  linearGradient: new Set(["gradientUnits", "x1", "y1", "x2", "y2"]),
  radialGradient: new Set(["gradientUnits", "cx", "cy", "r", "fx", "fy"]),
  stop: new Set(["offset", "stop-color", "stop-opacity"]),
};
const SVG_COLOR = /^(#[0-9a-fA-F]{3,8}|[a-zA-Z]+)$/;

/** Convert Graphviz's gradient stop style to bounded presentation attributes. */
function normalizeGradientStop(element: Element): void {
  const style = element.getAttribute("style");
  const match =
    style && /^stop-color:([^;]+);stop-opacity:([\d.]+);$/.exec(style);
  if (!match || !SVG_COLOR.test(match[1])) return;
  const opacity = Number(match[2]);
  if (!Number.isFinite(opacity) || opacity < 0 || opacity > 1) return;
  element.setAttribute("stop-color", match[1]);
  element.setAttribute("stop-opacity", String(opacity));
}

const ALLOWED_ATTRIBUTES = new Set([
  "class",
  "cx",
  "cy",
  "d",
  "fill",
  "font-family",
  "font-size",
  "font-style",
  "font-weight",
  "height",
  "id",
  "points",
  "preserveAspectRatio",
  "rx",
  "ry",
  "stroke",
  "stroke-dasharray",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-width",
  "target",
  "text-anchor",
  "transform",
  "viewBox",
  "width",
  "x",
  "x1",
  "x2",
  "xlink:title",
  "xml:space",
  "xmlns",
  "xmlns:xlink",
  "y",
  "y1",
  "y2",
]);

/** Protocols deliberately allowed for links generated by DOT's URL attribute. */
const SAFE_LINK_PROTOCOLS = new Set(["http", "https", "mailto", "obsidian"]);

export function isSafeSvgHref(value: string): boolean {
  const href = value.trim();
  if (href.startsWith("#")) return true;
  const scheme = /^([A-Za-z][A-Za-z0-9+.-]*):/.exec(href);
  return scheme !== null && SAFE_LINK_PROTOCOLS.has(scheme[1].toLowerCase());
}

/**
 * Apply a strict Graphviz-SVG allowlist before an element reaches the live DOM.
 * Unknown elements and attributes (including event handlers, arbitrary style,
 * foreign content, images, and unsafe link protocols) are removed. Gradient
 * stop styles are converted to presentation attributes; IDs and local references
 * are scoped to this diagram so inline SVGs cannot collide.
 */
export function sanitizeSvg(root: Element): Element {
  const elements = [root, ...Array.from(root.getElementsByTagName("*"))];
  for (const element of elements) {
    if (
      element.namespaceURI !== SVG_NS ||
      !ALLOWED_ELEMENTS.has(element.localName)
    ) {
      if (element !== root) element.parentNode?.removeChild(element);
      continue;
    }

    if (element.localName === "stop") normalizeGradientStop(element);

    for (const attribute of Array.from(element.attributes)) {
      const name = attribute.name;
      const isHref = name === "href" || name === "xlink:href";
      // Graphviz emits these presentation attributes for HTML-like labels.
      // Keep only its text formatting values, including combined decorations.
      const isTextFormatting =
        element.localName === "text" &&
        ((name === "baseline-shift" && /^(sub|super)$/.test(attribute.value)) ||
          (name === "text-decoration" &&
            /^(underline|overline|line-through)(,(underline|overline|line-through))*$/.test(
              attribute.value,
            )));
      if (
        (isHref &&
          element.localName === "a" &&
          isSafeSvgHref(attribute.value)) ||
        (!isHref &&
          (ALLOWED_ATTRIBUTES.has(name) ||
            GRADIENT_ATTRIBUTES[element.localName]?.has(name))) ||
        isTextFormatting
      ) {
        continue;
      }
      element.removeAttributeNode(attribute);
    }
  }

  const retained = [root, ...Array.from(root.getElementsByTagName("*"))];
  const prefix = `graphviz-plus-${++nextDiagramId}-`;
  const ids = new Map<string, string>();
  const gradients = new Set<string>();
  for (const [index, element] of retained.entries()) {
    const id = element.getAttribute("id");
    if (!id) continue;
    // Give even duplicate source IDs distinct DOM IDs; references use the first.
    const scoped = `${prefix}${index}`;
    if (!ids.has(id)) {
      ids.set(id, scoped);
      if (
        element.localName === "linearGradient" ||
        element.localName === "radialGradient"
      ) {
        gradients.add(id);
      }
    }
    element.setAttribute("id", scoped);
  }
  for (const element of retained) {
    for (const name of ["href", "xlink:href"]) {
      const href = element.getAttribute(name)?.trim();
      if (href?.startsWith("#")) {
        const scoped = ids.get(href.slice(1));
        if (scoped) element.setAttribute(name, `#${scoped}`);
      }
    }
    for (const name of ["fill", "stroke", "stop-color"]) {
      const paint = element.getAttribute(name);
      if (paint === null) continue;
      const reference = /^url\(#([^\s)]+)\)$/.exec(paint);
      if (reference && name !== "stop-color" && gradients.has(reference[1])) {
        element.setAttribute(name, `url(#${ids.get(reference[1])})`);
      } else if (!SVG_COLOR.test(paint)) {
        element.removeAttribute(name);
      }
    }
  }
  return root;
}

export function parseAndSanitizeSvg(svg: string): Element {
  assertSvgSize(svg);
  const doc = new DOMParser().parseFromString(svg, "image/svg+xml");
  const root = doc.documentElement;
  if (
    root.namespaceURI !== SVG_NS ||
    root.localName !== "svg" ||
    doc.getElementsByTagName("parsererror").length > 0
  ) {
    throw new Error("Graphviz returned output that is not valid SVG.");
  }
  return document.importNode(sanitizeSvg(root), true);
}
